/**
 * ข้อมูลของปุ่ม "ผลการแก้ไข" ที่บอทรับ (a=confirm&code=…&v=1|0)
 *
 * เดิมไฟล์นี้สร้างการ์ด "แก้ให้แล้ว ช่วยยืนยันหน่อย" ของระบบก่อน ต.ค. 2026 — ตั้งแต่ระบบเหลือ 2 สถานะ
 * (21 ต.ค. 2026) ไม่มีสถานะไหนส่งการ์ดนั้นแล้ว การปิดงานส่งการ์ดให้คะแนน (rating-card.ts) อย่างเดียว
 *
 * ที่ยังต้องเก็บฟังก์ชันนี้: การ์ดให้คะแนนใช้ v=0 กับปุ่ม "ยังมีปัญหาอยู่" และการ์ดยืนยันใบเก่ายังค้างอยู่ในห้องแชท
 * บอทรับปุ่มพวกนั้นทางเดียวคือรูปแบบนี้ — เปลี่ยนรูปเมื่อไหร่ ปุ่มบนการ์ดที่ส่งไปแล้วทุกใบกดไม่ติดทันที
 */

/** ใช้ ticket_code ไม่ใช่ id ภายใน เพราะ (1) สั้นกว่า ไม่เสี่ยงชน 300 ไบต์ของ postback
 *  (2) เป็นเลขที่ผู้ใช้เห็นอยู่แล้ว ดีบักจาก log ได้ทันทีโดยไม่ต้องเปิดฐานข้อมูล
 *  v=1 คือเรียบร้อย (การ์ดเก่า) · v=0 คือยังไม่หาย / ยังมีปัญหาอยู่ */
export function buildConfirmPostbackData(ticketCode: string, ok: boolean): string {
  return `a=confirm&code=${ticketCode}&v=${ok ? 1 : 0}`;
}
