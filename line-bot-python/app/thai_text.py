"""ทำความสะอาดข้อความไทยก่อนเข้าชั้น NLP + คลังคำพ้องศัพท์ IT

ทำไมต้องมีไฟล์นี้ (ไม่ใช่ปล่อยให้ ai.py จัดการเอง):
  ชั้นค้นหาทุกตัวใน ai.py — TF-IDF/BM25, fuzzy matching, การจับคีย์เวิร์ด — ล้วน "เทียบตัวอักษร"
  ทั้งสิ้น แปลว่าถ้าตัวอักษรไม่ตรงกันเป๊ะตั้งแต่ต้น ทุกชั้นที่อยู่ถัดไปพังหมดโดยไม่มีทางกู้
  ตัวอย่างที่เจอจริงในแชทไทย:

    "เเป้นพิมพ์"  ผู้ใช้กด สระเอ (U+0E40) สองครั้ง แทน ไม้หันอากาศแอ (U+0E41)
                  ตาคนอ่านว่า "แป้นพิมพ์" แต่คอมพิวเตอร์เห็นเป็นคนละสตริงโดยสิ้นเชิง
                  fuzzy ratio ตกจาก 100 เหลือราว 80 และถ้าเป็นคำสั้นจะหลุด threshold ทันที
    "พังงงง"      ลากตัวอักษรซ้ำเพื่อเน้นอารมณ์ — tokenizer ตัดได้เป็นคำที่ไม่มีในพจนานุกรม
    "จอไม่ติดครับ" คำลงท้ายสุภาพปนเข้าไปใน token ทำให้คะแนน TF-IDF เจือจาง

  ทั้งหมดนี้แก้ได้ด้วยการ normalize "ก่อน" เข้าชั้นอื่น ซึ่งถูกกว่าและอธิบายได้ง่ายกว่า
  การไปเพิ่มความซับซ้อนให้โมเดลปลายทางมาก

หลักการที่ยึด:
  - normalize ต้อง "ไม่ทำลายความหมาย" — เราแก้เฉพาะสิ่งที่คนไทยอ่านแล้วตีความเหมือนกันอยู่แล้ว
  - ทุกกฎต้องย้อนอธิบายได้ว่าแก้เคสอะไร (เขียนกำกับไว้ทุกข้อ) เพื่อให้คนที่มาทีหลังกล้าแก้
"""

from __future__ import annotations

import re
import unicodedata

# ---------------------------------------------------------------- ตัวแปรร่วม

# เลขไทย -> อารบิก (ผู้ใช้บางคนพิมพ์ "๒ ตัว")
THAI_DIGITS = str.maketrans("๐๑๒๓๔๕๖๗๘๙", "0123456789")

# อักขระที่มองไม่เห็นแต่ทำให้สตริงไม่เท่ากัน — มาจากการ copy/paste จากเว็บหรือ Excel
_INVISIBLE = re.compile(r"[​‌‍﻿ ⁠]")

# สระเอซ้อนสองตัว = แอ (เคสพิมพ์ผิดที่พบบ่อยที่สุดในภาษาไทย)
# U+0E40 = เ, U+0E41 = แ ; ทำแบบเดียวกันกับ ำ ที่บางคนพิมพ์เป็น ํ + า
_DOUBLE_SARA_E = re.compile("เเ")

# คำลงท้ายสุภาพ/คำอุทาน ที่ไม่มีผลต่อความหมายของคำขอ แต่กินน้ำหนักในการจัดอันดับ
# ตัดเฉพาะตอนอยู่ท้ายประโยคหรือคั่นด้วยช่องว่าง ไม่ตัดกลางคำ (กัน "ครับ" ใน "ครับผม" หาย)
_POLITE_PARTICLES = (
    "ครับผม", "คร้าบ", "ครับ", "คับ", "ค่ะ", "คะ", "ค่า", "จ้า", "จ้าา", "จ๊ะ", "นะคะ", "นะครับ",
    "ฮะ", "ฮ่ะ", "ด้วยนะ", "หน่อยนะ",
)
_PARTICLE_PATTERN = re.compile(
    r"(?:^|\s)(?:" + "|".join(sorted(_POLITE_PARTICLES, key=len, reverse=True)) + r")(?=\s|$)"
)

# ไม้ยมก: "ต่างๆ" -> "ต่าง ต่าง" ไม่ช่วยอะไร แค่ตัดทิ้งพอ
_REPEAT_MARK = re.compile("ๆ")

# ตัวอักษรไทยที่เป็น "พยัญชนะ" — ใช้ตัดสินว่าการซ้ำเป็นการลากเสียงหรือเป็นตัวสะกดจริง
_THAI_CONSONANT = re.compile(r"[ก-ฮ]")


def _collapse_repeats(text: str) -> str:
    """ยุบตัวอักษรเดียวกันที่ซ้ำติดกันเกิน 2 ตัว ให้เหลือ 1 ตัว

    "พังงงง" -> "พัง" , "เสียยยย" -> "เสีย" , "ดีมากกกก" -> "ดีมาก"
    "goooood" -> "good"

    ทำไมตัดที่ "เกิน 2": ภาษาไทยมีคำที่มีพยัญชนะซ้ำติดกัน 2 ตัวจริงๆ เช่น "บรรทัด" "ธรรมดา"
    ถ้ายุบทุกการซ้ำจะทำลายคำที่ถูกต้องอยู่แล้ว จึงยุบเฉพาะที่ซ้ำ 3 ตัวขึ้นไป
    ซึ่งแทบไม่มีในคำไทยมาตรฐาน แต่พบตลอดในแชท
    """
    return re.sub(r"(.)\1{2,}", r"\1", text)


def normalize(text: str) -> str:
    """ทำข้อความให้อยู่ในรูปมาตรฐานก่อนส่งเข้าชั้นค้นหา/จับคีย์เวิร์ด

    ลำดับสำคัญ: unicode -> อักขระล่องหน -> สระซ้อน -> ตัวซ้ำ -> คำลงท้าย -> ช่องว่าง
    (ตัดคำลงท้ายหลังยุบตัวซ้ำ เพราะ "ครับบบบ" ต้องกลายเป็น "ครับ" ก่อนถึงจะถูกตัด)
    """
    if not text:
        return ""

    # NFC รวมสระ/วรรณยุกต์ที่แยก codepoint ให้เป็นตัวเดียวกันก่อน ไม่งั้นเทียบยังไงก็ไม่ตรง
    out = unicodedata.normalize("NFC", text)
    out = _INVISIBLE.sub("", out)
    out = _DOUBLE_SARA_E.sub("แ", out)
    out = out.translate(THAI_DIGITS)
    out = _REPEAT_MARK.sub(" ", out)
    out = _collapse_repeats(out)
    out = _PARTICLE_PATTERN.sub(" ", out)
    out = re.sub(r"\s+", " ", out).strip().lower()
    return out


# ---------------------------------------------------------------- คำพ้องศัพท์ IT

# แต่ละกลุ่มคือ "ของสิ่งเดียวกันที่คนเรียกต่างกัน" — ตัวแรกของกลุ่มคือคำมาตรฐานที่ใช้อ้างอิง
#
# ทำไมต้องมี: ชื่อของในสต็อกถูกตั้งโดยแอดมิน (เช่น "คีย์บอร์ด") แต่พนักงานพิมพ์มาว่า
# "แป้นพิมพ์" หรือ "คีบอด" ซึ่ง fuzzy matching ช่วยได้เฉพาะกรณีสะกดใกล้เคียง
# ส่วนคำที่ "คนละคำแต่ความหมายเดียวกัน" fuzzy ช่วยไม่ได้เลย ต้องมีตารางแบบนี้เท่านั้น
#
# เพิ่มคำใหม่ได้อิสระ ไม่ต้องแก้โค้ดส่วนอื่น — ดัชนีถูกสร้างจากตารางนี้ตอน import
SYNONYM_GROUPS: tuple[tuple[str, ...], ...] = (
    ("คีย์บอร์ด", "แป้นพิมพ์", "คีบอด", "keyboard"),
    ("เมาส์", "เม้าส์", "mouse", "เมา ส์"),
    ("จอ", "หน้าจอ", "มอนิเตอร์", "monitor", "จอภาพ", "จอคอม"),
    ("เครื่องพิมพ์", "ปริ้นเตอร์", "พริ้นเตอร์", "เครื่องปริ้น", "เครื่องปริ้นท์", "printer", "ปริ้น"),
    ("คอมพิวเตอร์", "คอม", "พีซี", "pc", "desktop", "เครื่องคอม"),
    ("โน้ตบุ๊ก", "โน๊ตบุ๊ค", "โน้ตบุ๊ค", "notebook", "laptop", "แล็ปท็อป", "เลปทอป"),
    ("อินเทอร์เน็ต", "เน็ต", "internet", "อินเตอร์เน็ต"),
    ("ไวไฟ", "wifi", "wi-fi", "ไวฟาย"),
    ("เราเตอร์", "router", "เร้าเตอร์", "เราท์เตอร์"),
    ("สายแลน", "lan", "สาย lan", "สายแลน"),
    ("อีเมล", "email", "เมล", "e-mail", "มel"),
    ("รหัสผ่าน", "พาสเวิร์ด", "password", "pass", "รหัส"),
    ("หมึก", "ตลับหมึก", "toner", "ink", "หมึกพิมพ์"),
    ("กระดาษ", "paper", "กระดาษ a4"),
    ("ยูเอสบี", "usb", "ยูเอสบี", "แฟลชไดรฟ์", "thumbdrive", "flashdrive"),
    ("สำรองไฟ", "ups", "เครื่องสำรองไฟ"),
    ("กล้องวงจรปิด", "cctv", "กล้อง", "กล้องวงจร"),
    ("โปรแกรม", "ซอฟต์แวร์", "software", "แอป", "application", "app"),
    ("ติดตั้ง", "ลง", "install", "setup", "เซ็ตอัพ"),
    ("เสีย", "พัง", "ชำรุด", "ใช้ไม่ได้", "ไม่ทำงาน", "ไม่ติด", "broken"),
)


def _build_synonym_index() -> dict[str, str]:
    """แปลงกลุ่มคำพ้องเป็น dict: ทุกคำ -> คำมาตรฐานของกลุ่ม (คำแรก)"""
    index: dict[str, str] = {}
    for group in SYNONYM_GROUPS:
        canonical = normalize(group[0])
        for word in group:
            index[normalize(word)] = canonical
    return index


SYNONYM_INDEX: dict[str, str] = _build_synonym_index()

# เรียงจากยาวไปสั้น เพื่อให้แทน "เครื่องปริ้นท์" ก่อน "ปริ้น" (ไม่งั้นได้ผลลัพธ์เพี้ยน)
_SYNONYM_ORDER: tuple[str, ...] = tuple(
    sorted((w for w in SYNONYM_INDEX if w), key=len, reverse=True)
)


def canonicalize(word: str) -> str:
    """แปลงคำเดียวให้เป็นคำมาตรฐานของกลุ่มคำพ้อง (ถ้าไม่รู้จักคืนคำเดิม)"""
    return SYNONYM_INDEX.get(normalize(word), normalize(word))


def expand_synonyms(text: str) -> str:
    """เติมคำมาตรฐานเข้าไปในข้อความ โดย "ไม่ลบ" คำเดิมทิ้ง

    คืนค่าเป็น "ข้อความเดิม + คำมาตรฐานที่เกี่ยวข้อง" เพื่อให้ชั้นค้นหาเห็นทั้งสองแบบ
    เช่น "เครื่องปริ้นไม่ทำงาน" -> "เครื่องปริ้นไม่ทำงาน เครื่องพิมพ์ เสีย"

    ทำไมไม่แทนที่ทับของเดิม: ถ้าแทนที่แล้วเดาผิด ข้อมูลต้นฉบับจะหายไปเลย
    การ "เติม" ทำให้แย่ที่สุดคือมีคำเกินมานิดหน่อย ซึ่ง BM25 ลดน้ำหนักให้อยู่แล้ว
    """
    base = normalize(text)
    if not base:
        return ""

    found: list[str] = []
    seen: set[str] = set()
    for word in _SYNONYM_ORDER:
        if word and word in base:
            canonical = SYNONYM_INDEX[word]
            if canonical != word and canonical not in seen and canonical not in base:
                seen.add(canonical)
                found.append(canonical)

    return base if not found else f"{base} {' '.join(found)}"


# ---------------------------------------------------------------- การปฏิเสธ

# คำปฏิเสธที่อยู่ "ก่อน" คำกริยา ในภาษาไทย — ใช้ตัดสินว่าคีย์เวิร์ดที่เจอถูกปฏิเสธอยู่หรือไม่
NEGATION_WORDS: tuple[str, ...] = ("ไม่ได้", "ยังไม่", "ไม่", "มิได้", "ไม่มี", "หาย")

# ระยะ (จำนวนตัวอักษร) ที่นับว่าคำปฏิเสธ "ครอบคลุม" คำที่ตามมา
# 8 มาจากคำไทยทั่วไปยาว 3-6 ตัวอักษร + เผื่อคำขยาย 1 คำ เช่น "ยังไม่ค่อยเสีย"
_NEGATION_WINDOW = 8


def is_negated(text: str, keyword: str) -> bool:
    """เช็คว่าคีย์เวิร์ดที่เจอในประโยค ถูกคำปฏิเสธนำหน้าอยู่หรือเปล่า

    "คีย์บอร์ดเสีย"        -> False (แจ้งซ่อมจริง)
    "คีย์บอร์ดยังไม่เสีย"   -> True  (ไม่ใช่การแจ้งซ่อม)
    "ไม่ได้เบิกของ"        -> True

    ข้อจำกัดที่ยอมรับ: ใช้ระยะตัวอักษรตัดสิน ไม่ได้ parse ไวยากรณ์จริง
    ภาษาไทยไม่มีตัวคั่นคำ การ parse เต็มรูปแบบต้องใช้โมเดลหนักซึ่งเกินความจำเป็นของงานนี้
    วิธีนี้แก้เคสที่เจอบ่อยที่สุดได้ด้วยโค้ดไม่กี่บรรทัดและอธิบายได้ทุกบรรทัด
    """
    haystack = normalize(text)
    needle = normalize(keyword)
    if not haystack or not needle:
        return False

    start = haystack.find(needle)
    while start != -1:
        window = haystack[max(0, start - _NEGATION_WINDOW) : start]
        if any(neg in window for neg in NEGATION_WORDS):
            return True
        start = haystack.find(needle, start + 1)
    return False
