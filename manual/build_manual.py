def data_uri(path):
    return 'data:image/' + ('png' if path.suffix == '.png' else 'jpeg') + ';base64,' + base64.b64encode(path.read_bytes()).decode()

def html_block(block):
    kind, value = block
    if kind == 'table':
        return '<table>' + ''.join('<tr>' + ''.join(f'<{"th" if i==0 else "td"}>{html.escape(x)}</{"th" if i==0 else "td"}>' for x in row) + '</tr>' for i,row in enumerate(value)) + '</table>'
    if kind == 'steps':
        return '<ol>' + ''.join('<li>'+html.escape(x)+'</li>' for x in value) + '</ol>'
    return f'<{"h2" if kind=="h" else "p"} class="{kind}">' + html.escape(value).replace('\n','<br>') + f'</{"h2" if kind=="h" else "p"}>'

